/**
 * OpportunityPoster — branded 1080×1080 / 1080×1350 social graphic.
 *
 * Brand system: uses the REAL ARIA HUB logo (/images/logo-mark.png — navy
 * Kufic "آریا" mark) and the palette extracted from it: deep navy #283868
 * family + warm gold #F8D898 family. No invented accent colors.
 *
 * Used by:
 *  - /[lang]/social-poster (public full-size renderer, screenshotted for samples)
 *  - admin Social Kit panel (html-to-image PNG export)
 *
 * Fixed pixel dimensions + inline styles for pixel-exact export. Content is
 * pre-localized by the parent (title/org/salary/category via getLocalizedContent).
 * `qrDataUrl` (optional) is generated by the parent (server or client) and
 * rendered inside the gold CTA band — scan → listing page.
 */

export interface PosterData {
  slug: string;
  title: string;
  organization: string;
  country: string;
  deadline: string | null; // ISO
  salary: string;
  category: string;
  featured: boolean;
}

export type PosterSize = 'square' | 'portrait' | 'story';

/** Hex → rgba() with the original alpha of each legacy token. */
function rgbaOf(hex: string, alpha: number): string {
  const n = hex.replace('#', '');
  const r = parseInt(n.slice(0, 2), 16);
  const g = parseInt(n.slice(2, 4), 16);
  const b = parseInt(n.slice(4, 6), 16);
  return `rgba(${r},${g},${b},${alpha})`;
}

/**
 * Palette for this poster instance — derived from the Studio theme system so
 * spotlight posters respond to the same theme picker as every other canvas.
 * Key names match the original hardcoded palette (zero call-site churn).
 */
function paletteOf(themeId?: string) {
  const t = resolveTheme(themeId);
  return {
    bgTop: t.bgTop,
    bgMid: t.bgMid,
    bgBottom: t.bgBottom,
    navyDeep: t.deep,
    gold: t.accent,
    goldSoft: rgbaOf(t.accent, 0.8),
    goldLine: rgbaOf(t.accent, 0.42),
    goldFaint: rgbaOf(t.accent, 0.13),
    glowA: rgbaOf(t.accent, 0.14),
    white: t.text,
    textDim: t.textDim,
    ctaFrom: t.ctaFrom,
    ctaTo: t.ctaTo,
    logoSrc: '/images/logo-mark.png',
  };
}

const W = 1080;
const H: Record<PosterSize, number> = { square: 1080, portrait: 1350, story: 1920 };

function titleSize(title: string): number {
  const n = title.length;
  if (n > 120) return 46;
  if (n > 90) return 54;
  if (n > 60) return 66;
  if (n > 34) return 78;
  return 92;
}

export function OpportunityPoster({
  data,
  lang,
  size = 'square',
  qrDataUrl,
  themeId,
}: {
  data: PosterData;
  lang: Lang;
  size?: PosterSize;
  qrDataUrl?: string | null;
  themeId?: string;
}) {
  const t = (key: string, params?: Record<string, string | number>) => translate(lang, key, params);
  const rtl = lang !== 'en';
  const h = H[size];
  const portrait = size !== 'square'; // story behaves like portrait-plus
  const pad = size === 'story' ? 96 : portrait ? 84 : 72;
  const C = paletteOf(themeId);

  const deadline = data.deadline ? new Date(data.deadline) : null;
  const daysLeft = deadline
    ? Math.ceil((deadline.getTime() - Date.now()) / (24 * 60 * 60 * 1000))
    : null;
  const expired = daysLeft !== null && daysLeft < 0;
  const urgent = daysLeft !== null && daysLeft >= 0 && daysLeft <= 7;
  const daysLabel =
    daysLeft === null
      ? null
      : expired
        ? t('poster.expired')
        : daysLeft === 0
          ? t('poster.today')
          : daysLeft === 1
            ? t('poster.dayLeft')
            : t('poster.daysLeft', { n: toEasternDigits(String(daysLeft), lang) });

  const pill = expired
    ? { bg: 'rgba(248,113,113,0.16)', fg: '#fecaca', bd: 'rgba(248,113,113,0.45)', dot: '#f87171' }
    : urgent
      ? { bg: 'rgba(251,191,36,0.16)', fg: '#fde68a', bd: 'rgba(251,191,36,0.5)', dot: '#fbbf24' }
      : { bg: 'rgba(52,211,153,0.14)', fg: '#a7f3d0', bd: 'rgba(52,211,153,0.42)', dot: '#34d399' };

  return (
    <div
      dir={rtl ? 'rtl' : 'ltr'}
      style={{
        width: W,
        height: h,
        position: 'relative',
        overflow: 'hidden',
        background: `linear-gradient(168deg, ${C.bgTop} 0%, ${C.bgMid} 46%, ${C.bgBottom} 100%)`,
        fontFamily: 'var(--font-vazirmatn), sans-serif',
        color: C.white,
        display: 'flex',
        flexDirection: 'column',
        flexShrink: 0,
        flexGrow: 0,
      }}
    >
      {/* ── ambience: glows + dot grid + giant logo watermark ── */}
      <div
        style={{
          position: 'absolute',
          top: -200,
          insetInlineEnd: -170,
          width: 560,
          height: 560,
          borderRadius: '50%',
          background: `radial-gradient(circle, ${C.glowA} 0%, rgba(0,0,0,0) 68%)`,
        }}
      />
      <div
        style={{
          position: 'absolute',
          bottom: -240,
          insetInlineStart: -190,
          width: 660,
          height: 660,
          borderRadius: '50%',
          background: 'radial-gradient(circle, rgba(255,255,255,0.07) 0%, rgba(255,255,255,0) 70%)',
        }}
      />
      <div
        style={{
          position: 'absolute',
          inset: 0,
          backgroundImage: 'radial-gradient(rgba(255,255,255,0.09) 1.4px, transparent 1.4px)',
          backgroundSize: '36px 36px',
          opacity: 0.3,
        }}
      />
      {/* giant watermark of the REAL logo, quiet brand texture */}
      <img
        src={C.logoSrc}
        alt=""
        aria-hidden="true"
        style={{
          position: 'absolute',
          bottom: portrait ? -150 : -130,
          insetInlineEnd: -140,
          width: 640,
          height: 640,
          opacity: 0.06,
          pointerEvents: 'none',
        }}
      />

      {/* ── top gold hairline ── */}
      <div
        style={{
          position: 'absolute',
          top: 0,
          insetInlineStart: 0,
          width: '100%',
          height: 10,
          background: `linear-gradient(90deg, ${C.gold} 0%, ${C.gold} 34%, ${C.goldSoft} 70%, ${C.goldFaint} 100%)`,
        }}
      />

      {/* ── header: real logo + wordmark ── */}
      <div
        style={{
          position: 'relative',
          display: 'flex',
          alignItems: 'center',
          gap: 24,
          padding: `${portrait ? 74 : 62}px ${pad}px 0`,
        }}
      >
        <div
          style={{
            width: 88,
            height: 88,
            borderRadius: 24,
            overflow: 'hidden',
            flexShrink: 0,
            boxShadow: '0 14px 36px rgba(0,0,0,0.42)',
            outline: `2px solid ${C.goldLine}`,
            outlineOffset: -2,
          }}
        >
          <img src={C.logoSrc} alt="ARIA HUB" style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }} />
        </div>
        <div style={{ display: 'flex', flexDirection: 'column', gap: 6, minWidth: 0 }}>
          <div style={{ fontSize: 42, fontWeight: 800, letterSpacing: 3, lineHeight: 1, direction: 'ltr', textAlign: rtl ? 'right' : 'left' }}>
            ARIA HUB
          </div>
          <div style={{ fontSize: 21, color: C.goldSoft, fontWeight: 500 }}>
            {t('poster.tagline')}
          </div>
        </div>
      </div>

      {/* ── chips ── */}
      <div
        style={{
          position: 'relative',
          display: 'flex',
          gap: 14,
          alignItems: 'center',
          flexWrap: 'wrap',
          padding: `0 ${pad}px`,
          marginTop: portrait ? 54 : 40,
        }}
      >
        {data.category ? (
          <span
            style={{
              fontSize: 24,
              fontWeight: 700,
              padding: '10px 26px',
              borderRadius: 999,
              background: C.goldFaint,
              border: `1.5px solid ${C.goldLine}`,
              color: C.gold,
            }}
          >
            {data.category}
          </span>
        ) : null}
        {data.featured ? (
          <span
            style={{
              fontSize: 24,
              fontWeight: 800,
              padding: '12px 28px',
              borderRadius: 999,
              display: 'inline-flex',
              alignItems: 'center',
              gap: 10,
              background: C.gold,
              color: C.navyDeep,
              boxShadow: '0 10px 26px rgba(248,216,152,0.28)',
            }}
          >
            <Sparkles style={{ width: 24, height: 24 }} />
            {t('poster.featured')}
          </span>
        ) : null}
      </div>

      {/* ── title block with editorial gold rule ── */}
      <div
        style={{
          position: 'relative',
          padding: `0 ${pad}px`,
          marginTop: 28,
          flex: 1,
          display: 'flex',
          flexDirection: 'column',
          justifyContent: 'center',
          minHeight: 0,
        }}
      >
        <div
          style={{
            width: 64,
            height: 7,
            borderRadius: 999,
            background: `linear-gradient(90deg, ${C.gold}, rgba(248,216,152,0.35))`,
            marginBottom: 26,
          }}
        />
        <div
          style={{
            fontSize: titleSize(data.title),
            fontWeight: 800,
            lineHeight: 1.24,
            letterSpacing: -0.5,
            display: '-webkit-box',
            WebkitLineClamp: portrait ? 4 : 3,
            WebkitBoxOrient: 'vertical',
            overflow: 'hidden',
            textShadow: '0 6px 30px rgba(0,0,0,0.4)',
          }}
        >
          {data.title}
        </div>

        <div
          style={{
            marginTop: 32,
            display: 'flex',
            flexDirection: 'column',
            gap: 16,
            fontSize: 30,
            color: 'rgba(255,255,255,0.94)',
            fontWeight: 500,
          }}
        >
          {data.organization ? (
            <div style={{ display: 'flex', alignItems: 'center', gap: 14, minWidth: 0 }}>
              <Building2 style={{ width: 32, height: 32, color: C.gold, flexShrink: 0, opacity: 0.9 }} />
              <span style={{ overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>
                {data.organization}
              </span>
            </div>
          ) : null}
          {data.country ? (
            <div style={{ display: 'flex', alignItems: 'center', gap: 14 }}>
              <MapPin style={{ width: 32, height: 32, color: C.gold, flexShrink: 0, opacity: 0.9 }} />
              <span>{data.country}</span>
            </div>
          ) : null}
          {data.salary ? (
            <div style={{ display: 'flex', alignItems: 'center', gap: 14 }}>
              <Banknote style={{ width: 32, height: 32, color: C.gold, flexShrink: 0 }} />
              <span style={{ fontWeight: 700, color: C.gold }}>{data.salary}</span>
            </div>
          ) : null}
        </div>
      </div>

      {/* ── deadline card ── */}
      {deadline ? (
        <div style={{ position: 'relative', padding: `0 ${pad}px`, marginBottom: 30 }}>
          <div
            style={{
              background: 'rgba(255,255,255,0.07)',
              border: `1.5px solid ${C.goldLine}`,
              borderRadius: 24,
              padding: '24px 30px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: 18,
              backdropFilter: 'blur(4px)',
            }}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: 18, minWidth: 0 }}>
              <CalendarDays style={{ width: 40, height: 40, color: C.gold, flexShrink: 0 }} />
              <div style={{ display: 'flex', flexDirection: 'column', gap: 2, minWidth: 0 }}>
                <span style={{ fontSize: 20, color: C.textDim, fontWeight: 600 }}>
                  {t('poster.applyBy')}
                </span>
                <span style={{ fontSize: 28, fontWeight: 700, whiteSpace: 'nowrap' }}>
                  {formatDateLong(deadline, lang)}
                </span>
              </div>
            </div>
            {daysLabel ? (
              <span
                style={{
                  fontSize: 22,
                  fontWeight: 800,
                  padding: '10px 22px',
                  borderRadius: 999,
                  whiteSpace: 'nowrap',
                  background: pill.bg,
                  color: pill.fg,
                  border: `1.5px solid ${pill.bd}`,
                  display: 'inline-flex',
                  alignItems: 'center',
                  gap: 10,
                }}
              >
                <span
                  style={{
                    width: 10,
                    height: 10,
                    borderRadius: '50%',
                    background: pill.dot,
                    boxShadow: `0 0 10px ${pill.dot}`,
                  }}
                />
                {daysLabel}
              </span>
            ) : null}
          </div>
        </div>
      ) : (
        <div style={{ height: 30 }} />
      )}

      {/* ── footer CTA band: solid brand gold (inverse of the navy canvas) ── */}
      <div
        style={{
          position: 'relative',
          margin: `0 ${pad}px ${portrait ? 66 : 54}px`,
          background: `linear-gradient(135deg, ${C.ctaFrom} 0%, ${C.ctaTo} 100%)`,
          color: C.navyDeep,
          borderRadius: 24,
          padding: '22px 30px',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          gap: 20,
          boxShadow: '0 20px 50px rgba(0,0,0,0.4)',
        }}
      >
        <div style={{ display: 'flex', flexDirection: 'column', gap: 3, minWidth: 0 }}>
          <span style={{ fontSize: 32, fontWeight: 800, direction: 'ltr', textAlign: rtl ? 'right' : 'left', letterSpacing: 0.5 }}>
            myariahub.com
          </span>
          <span style={{ fontSize: 21, fontWeight: 700, color: 'rgba(27,36,64,0.72)' }}>{t('poster.cta')}</span>
        </div>
        {qrDataUrl ? (
          <div
            style={{
              background: '#FFFBF2',
              borderRadius: 16,
              padding: 8,
              flexShrink: 0,
              boxShadow: 'inset 0 0 0 1.5px rgba(27,36,64,0.14)',
            }}
          >
            <img src={qrDataUrl} alt="QR" style={{ width: 84, height: 84, display: 'block' }} />
          </div>
        ) : (
          <div
            style={{
              width: 66,
              height: 66,
              borderRadius: 18,
              overflow: 'hidden',
              flexShrink: 0,
              outline: '2px solid rgba(27,36,64,0.35)',
              outlineOffset: -2,
            }}
          >
            <img src={C.logoSrc} alt="ARIA HUB" style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }} />
          </div>
        )}
      </div>

      {/* bottom gold strip */}
      <div
        style={{
          position: 'absolute',
          bottom: 0,
          insetInlineStart: 0,
          width: '100%',
          height: 12,
          background: `linear-gradient(90deg, ${C.gold} 0%, ${C.gold} 55%, ${C.goldSoft} 100%)`,
        }}
      />
    </div>
  );
}

/** Build poster data from a raw DB-shaped record (localized here, once). */
export function buildPosterData(
  opp: {
    slug: string;
    title: string;
    titleI18n: unknown;
    organization: string | null;
    country: string | null;
    deadline: Date | string | null;
    featured: boolean;
    salary: string | null;
    salaryI18n: unknown;
    category?: { name: string; nameI18n?: unknown } | null;
  },
  lang: Lang,
): PosterData {
  const i18n = (v: unknown) => (v && typeof v === 'object' ? (v as Record<string, string>) : null);
  return {
    slug: opp.slug,
    title: getLocalizedContent(opp.title, i18n(opp.titleI18n), lang) || opp.title,
    organization: opp.organization || '',
    country: opp.country || '',
    deadline: opp.deadline ? new Date(opp.deadline).toISOString() : null,
    salary: getLocalizedContent(opp.salary, i18n(opp.salaryI18n), lang),
    category: opp.category
      ? getLocalizedContent(opp.category.name, i18n(opp.category.nameI18n), lang) || opp.category.name
      : '',
    featured: opp.featured,
  };
}
